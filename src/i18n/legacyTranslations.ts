const enMap: Record<string, string> = {};

function phrase(key: string, language: "id" | "en"): string {
  const words = key
    .split(".")
    .slice(-3)
    .join(" ")
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/[_-]+/g, " ")
    .split(/\s+/)
    .filter(Boolean);
  const map = language === "id" ? idMap : enMap;
  return words.map((word) => map[word] ?? (word.charAt(0).toUpperCase() + word.slice(1))).join(" ");
}

