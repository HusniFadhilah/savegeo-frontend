/**
 * Lightweight `{placeholder}` interpolation on top of a translated string -
 * `t()` itself (useI18nStore) only does a flat key lookup, so any string
 * that needs a runtime value (a year, a name, an area) goes through this
 * after the lookup. Falls back to leaving `{key}` in place if no value was
 * supplied, so a missed param is visible instead of silently swallowed.
 */
export function interpolate(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key) => {
    const val = params[key];
    return val === undefined ? match : String(val);
  });
}




